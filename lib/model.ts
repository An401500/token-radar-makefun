// Token Radar's model: one sealed snapshot in, one ranked board out.
//
// The board ranks pre-token protocols by an implied value that is computed from the
// snapshot's own figures only, never from a hand-written list of names:
//
//   implied = TVL x peerMultiple x growthMult x maturityMult x chainMult
//
//   peerMultiple  the median market-cap-to-TVL ratio of the live-token protocols in
//                 the same category, read off the snapshot itself (n >= 3); clamped
//                 to [0.05, 1.50]; categories with too few live peers fall back to
//                 the overall live median. A lending protocol is priced like lending
//                 protocols that already trade, a DEX like DEXs that already trade.
//   growthMult    1 + clamp(change_7d, -60, +120) / 100 x 0.5
//   maturityMult  0.6 + min(age_days, 1095) / 1095 x 0.4 (age unknown: 365 days)
//   chainMult     1 + 0.02 x min(chains - 1, 5): a protocol live on more chains has
//                 wider distribution for a future token.
//
// A row is rankable only when it passes the same exclusion rule the house used for
// its watchlist: it records no token, and it is not a wrapped, staked or bridged
// product of a protocol whose token already trades (no Bridge / Canonical Bridge /
// Liquid Staking / Liquid Restaking / Restaked BTC / CEX category, no whole word
// wrapped / staked / staking in its name, no version marker, no exchange prefix).
// That keeps WBTC, Binance staked ETH, USDT0 and the like off the board entirely.
// The watchlist (40 slugs at or above the $50M floor) is the floor, never the
// ceiling: the board adds every other rankable protocol below the floor, so the
// radar also finds the early ones. Protocols above the floor that the watchlist
// leaves out are left out too: the snapshot carries no parentProtocol field, so
// the house's own rule cannot be re-checked for them, and the board does not guess.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

